export const APP_REGISTRY_MAP: Record<AppId, AppRegistryEntry> = Object.fromEntries(
  APP_REGISTRY.map((entry) => [entry.id, entry])
) as Record<AppId, AppRegistryEntry>;

export const RUN_ALIAS_MAP: Record<string, AppId> = (() => {
  const map: Record<string, AppId> = {};
  for (const entry of APP_REGISTRY) {
    for (const alias of entry.runAliases) {
      map[alias.toLowerCase()] = entry.id;
    }
  }
  return map;
})();

export function getExtension(fileName: string): string {
  const idx = fileName.lastIndexOf('.');
  return idx >= 0 ? fileName.slice(idx).toLowerCase() : '';
}

export function resolveAppForFile(
  fileName: string,
  kind: NodeKind,
  fileAssociations: Record<string, AppId>
): AppId {
  const ext = getExtension(fileName);
  if (ext && fileAssociations[ext]) {
    return fileAssociations[ext];
  }
  switch (kind) {
    case 'rtf':
      return 'wordpad';
    case 'image':
      return 'imageviewer';
    case 'audio':
      return 'wmplayer';
    case 'project':
      return 'moviemaker';
    case 'archive':
      return 'explorer';
    default:
      return 'notepad';
  }
}

export function isAppInstalled(
  appId: AppId,
  optionalComponents: Record<string, boolean>
): boolean {
  const entry = APP_REGISTRY_MAP[appId];
  if (!entry || !entry.optionalComponentId) return true;
  return Boolean(optionalComponents[entry.optionalComponentId]);
}
