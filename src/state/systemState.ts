export function appendEventLog(
  state: SystemState,
  entry: Omit<EventLogEntry, 'id' | 'timestamp'>
): SystemState {
  const newEntry: EventLogEntry = {
    ...entry,
    id: `evt_${Date.now()}_${Math.random().toString(36).slice(2, 6)}`,
    timestamp: Date.now(),
  };
  return {
    ...state,
    eventLog: [newEntry, ...state.eventLog].slice(0, 120),
  };
}
